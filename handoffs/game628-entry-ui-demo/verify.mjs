import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';

const url = 'http://127.0.0.1:18841/';
const browser = await chromium.launch({executablePath:process.env.RENDER_PROBE_CHROMIUM ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--enable-unsafe-swiftshader']});
const results=[];
await mkdir(new URL('./evidence/',import.meta.url),{recursive:true});
try {
  for(const size of [{width:1280,height:800},{width:390,height:844}]){
    const page=await browser.newPage({viewport:size});
    const errors=[], failedRequests=[];
    page.on('response',response=>{if(response.status()>=400)failedRequests.push([response.status(),new URL(response.url()).pathname]);});
    page.on('pageerror',error=>errors.push(String(error)));
    page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('favicon'))errors.push(message.text());});
    await page.goto(url);
    const click=async id=>page.locator('#'+id).click();
    const screenshot=async name=>page.screenshot({path:new URL(`./evidence/${size.width}-${name}.png`,import.meta.url).pathname});
    await page.locator('#start').waitFor();
    await screenshot('home');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.id),'start');
    await page.keyboard.press('Enter');
    await page.locator('#login-title').waitFor();
    await screenshot('login');
    await click('login-confirm');
    await page.locator('#confirm:enabled').waitFor({timeout:20000});
    const frame=page.frameLocator('#preview');
    await frame.locator('#eyes-1').click();
    await page.waitForTimeout(250);
    await screenshot('face');
    await click('confirm');
    await page.locator('#entry[data-screen="street"][data-confirmed-face^="1"]').waitFor();
    await page.locator('#instructions').waitFor({timeout:20000});
    const street=page.frames().find(f=>f.url().includes('reference-walk'));
    assert.ok(street);
    assert.ok(await street.evaluate(()=>window.apolloPrototype.stats().models>0));
    const position=()=>street.evaluate(()=>JSON.stringify(window.apolloPrototype.snapshot().player?.Transform));
    const before=await position();
    await page.locator('#preview').focus();
    await page.keyboard.down('d');
    await page.waitForTimeout(300);
    await page.keyboard.up('d');
    assert.notEqual(await position(),before);
    await page.keyboard.press('Escape');
    await page.locator('#continue').waitFor();
    const paused=await position();
    await page.keyboard.down('d');await page.waitForTimeout(180);await page.keyboard.up('d');
    assert.equal(await position(),paused);
    await screenshot('menu');
    await click('settings');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.id),'return-settings');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.type),'range');
    const slider=page.locator('#gain input');
    await slider.focus();await page.keyboard.press('Home');await page.keyboard.press('ArrowRight');
    assert.equal(await slider.inputValue(),'5');
    await click('sound');
    await click('hints');
    await screenshot('settings');
    await page.keyboard.press('Escape');
    await page.locator('#continue').waitFor();
    await click('continue');
    assert.equal(await page.locator('#instructions').count(),0);
    await click('settings');
    assert.equal(await slider.inputValue(),'5');
    await click('return-settings');
    await click('menu');
    await click('title');
    await click('guest');
    await page.locator('#confirm:enabled').waitFor({timeout:20000});
    await click('back');
    await page.locator('#start').waitFor();
    await click('guest');
    await page.locator('#confirm:enabled').waitFor({timeout:20000});
    await click('confirm');
    await page.locator('#entry[data-screen="street"][data-confirmed-face="0000"]').waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors.filter(x=>!x.includes('404')),[]);
    results.push({size,realStreet:true,faceChangedAndConfirmed:true,keyboard:true,menuInputBlocked:true,settingsAndReentry:true,errors,failedRequests});
    await page.close();
  }
  console.log(JSON.stringify(results,null,2));
  await writeFile(new URL('./evidence/verification.json',import.meta.url),JSON.stringify(results,null,2)+'\n');
}finally{await browser.close();}
